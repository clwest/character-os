"""End-to-end smoke test for the SESSION 108 contract slice.

Exercises the full Phase 2 pipeline:

    DRF view  →  TeammateViewSet.perform_create
              →  MediaEngineClient.create_avatar
              →  POST /internal/avatars/ on FastAPI media-engine
              →  studio_create_avatar (mock-mode short-circuit)
              →  back through the wire
              →  Teammate row gets runway_avatar_id + status persisted

Run with the FastAPI media-engine listening on :8001 (mock mode is
fine; in fact preferred — no Runway credits burned). Defaults to a
1×1 transparent PNG portrait so the test is hermetic.

Usage:
    python manage.py smoke_avatar
    python manage.py smoke_avatar --workspace-slug acme

Exit codes:
    0 — avatar id persisted, status ∈ {ready, mock}
    1 — anything else (media-engine unreachable, validation failure,
        avatar status failed)
"""
from __future__ import annotations

import sys
from typing import Any

from django.contrib.auth import get_user_model
from django.core.management.base import BaseCommand
from django.db import transaction

from apps.accounts.models import Membership, Workspace
from apps.spokespeople.models import Teammate
from character_os.clients.media_engine import (
    MediaEngineClient,
    MediaEngineError,
)

# 1×1 transparent PNG. Tiny, deterministic, no fixture file needed.
_TRANSPARENT_PNG_B64 = (
    "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNkYAAAAAYAAjCB0C8AAAAASUVORK5CYII="
)
_TRANSPARENT_PNG_DATA_URI = "data:image/png;base64," + _TRANSPARENT_PNG_B64

User = get_user_model()


class Command(BaseCommand):
    help = (
        "Smoke-test the SESSION 108 contract: spokesperson create → "
        "/internal/avatars/ → runway_avatar_id persisted."
    )

    def add_arguments(self, parser) -> None:
        parser.add_argument(
            "--workspace-slug",
            default=None,
            help="Pick an existing workspace by slug. Defaults to first.",
        )
        parser.add_argument(
            "--name",
            default="Smoke Test Teammate",
            help="Name to use for the test spokesperson.",
        )
        parser.add_argument(
            "--keep",
            action="store_true",
            help="Keep the created spokesperson row (default: delete on exit).",
        )

    def handle(self, *args: Any, **opts: Any) -> None:
        # 1 — verify the media-engine is reachable. Fail fast with a
        # helpful message rather than letting the create call blow up
        # mid-transaction.
        try:
            with MediaEngineClient() as client:
                health = client.health_check()
        except MediaEngineError as exc:
            self.stderr.write(
                self.style.ERROR(
                    f"media engine unreachable — start it on :8001 first ({exc})"
                )
            )
            sys.exit(1)
        self.stdout.write(
            f"  ✓ media engine reachable (runway_mock={health.runway_mock})"
        )

        # 2 — pick a workspace + owner. Smoke test assumes the bootstrap
        # signup flow has run at least once so there's a Workspace.
        workspace = self._pick_workspace(opts["workspace_slug"])
        if workspace is None:
            self.stderr.write(
                self.style.ERROR(
                    "no Workspace rows in the DB. Run the signup flow once "
                    "first: POST /accounts/signup/."
                )
            )
            sys.exit(1)
        self.stdout.write(
            f"  ✓ using workspace {workspace.slug!r} (id={workspace.pk})"
        )

        # 3 — exercise the same code path the DRF viewset would: call
        # `perform_create` via a fake serializer save. Simpler than
        # spinning up a test client and forging auth.
        from apps.spokespeople.serializers import TeammateSerializer
        from apps.spokespeople.views import TeammateViewSet

        owner = workspace.owner
        request = _StubRequest(owner)
        serializer = TeammateSerializer(
            data={
                "workspace": str(workspace.pk),
                "name": opts["name"],
                "business_brief": "Smoke test — generated by manage.py smoke_avatar.",
                "portrait_data_uri": _TRANSPARENT_PNG_DATA_URI,
                "voice_preset": "vincent",
            },
            context={"request": request},
        )
        serializer.is_valid(raise_exception=True)

        viewset = TeammateViewSet()
        viewset.request = request  # type: ignore[assignment]

        sid = None
        try:
            with transaction.atomic():
                viewset.perform_create(serializer)
                instance: Teammate = serializer.instance  # type: ignore[assignment]
                sid = instance.pk

                self.stdout.write(
                    f"  ✓ spokesperson row created id={instance.pk}"
                )
                self.stdout.write(
                    f"    runway_avatar_id     = {instance.runway_avatar_id!r}"
                )
                self.stdout.write(
                    f"    runway_avatar_status = {instance.runway_avatar_status!r}"
                )
                self.stdout.write(
                    f"    status               = {instance.status!r}"
                )

                ok = (
                    bool(instance.runway_avatar_id)
                    and instance.runway_avatar_status in {"ready", "mock"}
                )
                if not ok:
                    self.stderr.write(
                        self.style.ERROR(
                            "smoke test FAILED — avatar id missing or status not ready/mock"
                        )
                    )
                    raise _SmokeFailed()

                # Rollback the test row unless --keep.
                if not opts["keep"]:
                    raise _SmokeOk()
        except _SmokeOk:
            self.stdout.write(self.style.SUCCESS("✓ smoke test PASSED (row rolled back)"))
            return
        except _SmokeFailed:
            sys.exit(1)

        # --keep path lands here.
        self.stdout.write(
            self.style.SUCCESS(f"✓ smoke test PASSED (row id={sid} kept)")
        )

    @staticmethod
    def _pick_workspace(slug: str | None) -> Workspace | None:
        qs = Workspace.objects.all().order_by("created_at")
        if slug:
            return qs.filter(slug=slug).first()
        return qs.first()


class _StubRequest:
    """Minimal stand-in for a DRF Request. Carries an authenticated
    user — that's all the Teammate serializer / viewset code path
    actually reads."""

    def __init__(self, user) -> None:
        self.user = user


class _SmokeOk(Exception):
    """Sentinel raised after a successful run to roll back the atomic
    block so the test doesn't leave junk rows behind."""


class _SmokeFailed(Exception):
    """Sentinel raised on assertion failure so the atomic block also
    rolls back."""


# Silence "Membership" unused import in some import orderings.
_ = Membership
